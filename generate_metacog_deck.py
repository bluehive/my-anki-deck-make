def validate_cards(cards: list[tuple[str, str, str]]) -> None:
    if len(cards) != EXPECTED_TOTAL:
        raise SystemExit(f"件数不一致: {len(cards)} != {EXPECTED_TOTAL}")

    fronts: set[str] = set()
    for i, (front, back, category) in enumerate(cards, 1):
        if not front.strip() or not back.strip() or not category.strip():
            raise SystemExit(f"カード{i}: 空欄がある")
        if "{{c" in front or "{{c" in back:
            raise SystemExit(f"カード{i}: Cloze記法（{{{{c）を含んでいる")
        if front in fronts:
            raise SystemExit(f"カード{i}: 表面が重複している: {front}")
        fronts.add(front)
        if not front.endswith("？"):
            raise SystemExit(f"カード{i}: 表面が「？」で終わっていない: {front}")
        if len(back) > BACK_MAX_LEN:
            raise SystemExit(
                f"カード{i}: 裏面が{BACK_MAX_LEN}文字を超えている（{len(back)}文字）: {back}"
            )


def write_csv(cards: list[tuple[str, str, str]]) -> None:
    with open(OUTPUT, "w", encoding="utf-8", newline="") as f:
        writer = csv.writer(f, quoting=csv.QUOTE_ALL)
        writer.writerow(["表面", "裏面", "カテゴリ"])
        for front, back, category in cards:
            writer.writerow([front, back, category])


def main() -> None:
    validate_cards(CARDS)
    write_csv(CARDS)
    print(f"✓ {OUTPUT} を生成しました（{len(CARDS)}問 / Basic / 列: 表面,裏面,カテゴリ）")


if __name__ == "__main__":
    try:
        main()
    except BrokenPipeError:
        sys.exit(0)
