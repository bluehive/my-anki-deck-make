def validate_cards(cards: list[tuple[str, str]]) -> None:
    if len(cards) > 50:
        raise SystemExit(f"枚数上限超過: {len(cards)} > 50")
    if len(cards) != EXPECTED_TOTAL:
        raise SystemExit(f"件数不一致: {len(cards)} != {EXPECTED_TOTAL}")

    cloze = re.compile(r"\{\{c(\d+)::(.*?)\}\}", re.DOTALL)
    for i, (text, tag) in enumerate(cards, 1):
        if not tag.strip():
            raise SystemExit(f"カード{i}: タグが空")
        hits = cloze.findall(text)
        if len(hits) != 1 or hits[0][0] != "1":
            raise SystemExit(f"カード{i}: 穴は c1 がちょうど 1 つであること（実際 {hits}）")
        answer = hits[0][1].strip()
        if not answer:
            raise SystemExit(f"カード{i}: 答えが空")
        visible = cloze.sub("____", text)
        if answer in visible:
            raise SystemExit(f"カード{i}: 答えが表面に残っている: {answer}")


def write_csv(cards: list[tuple[str, str]]) -> None:
    with open(OUTPUT, "w", encoding="utf-8", newline="") as f:
        writer = csv.writer(f, quoting=csv.QUOTE_ALL)
        writer.writerow(["Text", "Tag", "Deck"])
        for text, tag in cards:
            writer.writerow([text, tag, DECK_TITLE])


def main() -> None:
    validate_cards(CARDS)
    write_csv(CARDS)
    print(f"✓ {OUTPUT} を生成しました（{len(CARDS)}問 / 上限50 / デッキ: {DECK_TITLE}）")


if __name__ == "__main__":
    try:
        main()
    except BrokenPipeError:
        sys.exit(0)
